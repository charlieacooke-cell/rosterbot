def main():
    root = Path(__file__).parent
    csv_path = Path(CSV_FILE)
    if not csv_path.exists():
        print(f"❌ CSV not found: {csv_path}")
        return

    print("🔁 Reg Swap Board Generator")
    print("=" * 40)
    payload = parse_roster(csv_path)

    (root / "swaps").mkdir(exist_ok=True)
    password = read_password(root)
    (root / OUT_HTML).write_text(generate_html(), encoding="utf-8")
    (root / OUT_FUNC).write_text(generate_func(payload, password), encoding="utf-8")
    print(f"🌐 Wrote {OUT_HTML}")
    print(f"⚙️  Wrote {OUT_FUNC}  (password baked in; file is gitignored)")
    print("\n✅ Done. Deploy with: netlify deploy --prod --dir swaps --site <swap-site-id>")

