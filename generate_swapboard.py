FUNC_TEMPLATE = r"""// AUTO-GENERATED by generate_swapboard.py — do not edit by hand.
import { getStore } from "@netlify/blobs";

const PAYLOAD = __PAYLOAD__;
const SHARED_PW = "__PASSWORD__";   // baked in at generate time; this file is gitignored
const STORE  = "reg-swaps";
const PREFIX = "flag:";             // one blob per flag → concurrent toggles never clobber

const cors = {
  "Access-Control-Allow-Origin":  "*",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
  "Access-Control-Allow-Headers": "Content-Type",
};

export default async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { status: 204, headers: cors });
  if (req.method !== "POST")    return new Response("Method not allowed", { status: 405, headers: cors });

  let body;
  try { body = await req.json(); } catch { return j({ error: "bad request" }, 400); }

  // env var wins if present (CI deploys); otherwise the baked-in password.
  const truth = process.env.SWAP_PASSWORD || SHARED_PW;
  const pw = body.password || "";
  if (!truth || pw !== truth) return j({ error: "unauthorized" }, 401);

  const store = getStore(STORE);

  if (body.action === "load") {
    const flags = {};
    try {
      const { blobs } = await store.list({ prefix: PREFIX });
      for (const b of blobs) {
        const v = await store.get(b.key, { type: "json" });
        if (v) flags[b.key.slice(PREFIX.length)] = v;
      }
    } catch { /* return whatever we have */ }
    return j({ ok: true, payload: PAYLOAD, flags });
  }

  if (body.action === "flag") {
    const { date, person, by, on } = body;
    if (!date || !person) return j({ error: "missing date/person" }, 400);
    const key = `${PREFIX}${date}|${person}`;
    try {
      if (on) await store.set(key, JSON.stringify({ by: by || person, at: Date.now() }));
      else    await store.delete(key);
    } catch (e) { return j({ error: "storage: " + e.message }, 500); }
    return j({ ok: true });   // client keeps its own optimistic state
  }

  return j({ error: "unknown action" }, 400);
};

function j(obj, status = 200) {
  return new Response(JSON.stringify(obj), {
    status, headers: { ...cors, "Content-Type": "application/json" },
  });
}

export const config = { path: "/api/roster" };
"""

def read_password(root):
    """Password comes from env SWAP_PW, else the gitignored file swaps/.password."""
    import os
    pw = os.environ.get("SWAP_PW", "").strip()
    if pw:
        return pw
    pwfile = root / "swaps" / ".password"
    if pwfile.exists():
        return pwfile.read_text().strip()
    raise SystemExit("No password set. Put it in swaps/.password or set SWAP_PW env var.")

def generate_func(payload, password):
    return (FUNC_TEMPLATE
            .replace("__PAYLOAD__", json.dumps(payload, separators=(",", ":")))
            .replace("__PASSWORD__", password))

