def parse_roster(csv_path):
    rows = list(csv.reader(open(csv_path, encoding="utf-8-sig")))
    hdr = rows[0]

    people = []
    for i in range(3, len(hdr)):
        name = hdr[i].strip()
        if not name:
            break
        people.append((i, name))
    people_names = [n for _, n in people]

    roster = {}       # iso -> {person: code}
    dates  = []       # ordered iso
    weeks  = []       # [{label, dates:[iso]}]
    cur_week_label = None
    cur_week = None

    for r in rows[1:]:
        if len(r) < 3:
            continue
        wlabel = r[0].strip()
        try:
            d = datetime.strptime(r[2].strip(), "%d-%b-%y").date()
        except ValueError:
            continue
        iso = d.isoformat()
        dates.append(iso)

        if wlabel:
            cur_week_label = wlabel
            cur_week = {"label": wlabel, "dates": []}
            weeks.append(cur_week)
        if cur_week is None:
            cur_week = {"label": cur_week_label or "", "dates": []}
            weeks.append(cur_week)
        cur_week["dates"].append(iso)

        day = {}
        for i, name in people:
            code = r[i].strip() if i < len(r) else ""
            if code and code not in ("0", "1"):
                day[name] = code
        roster[iso] = day

    # code metadata actually present
    seen = {c for day in roster.values() for c in day.values()}
    meta = {c: {"label": meta_for(c)[0], "type": meta_for(c)[1],
                "flaggable": meta_for(c)[1] in FLAGGABLE_TYPES}
            for c in seen}

    payload = {
        "people": people_names,
        "dates":  dates,
        "weeks":  weeks,
        "roster": roster,
        "meta":   meta,
    }
    print(f"  ✓ {len(people_names)} registrars, {len(dates)} days, {len(weeks)} weeks")
    return payload

